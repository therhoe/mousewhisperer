// Native Node checks for display-only branding changes and stable integrations.
/* eslint jest/no-deprecated-functions: "off", jest/expect-expect: ["error", { "assertFunctionNames": ["assert", "assert.*"] }] */
import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import test from "node:test";

const read = (path) =>
  readFileSync(new URL(`../${path}`, import.meta.url), "utf8");
const tomlString = (content, name) =>
  content.match(new RegExp(`^\\s*${name}\\s*=\\s*"([^"]*)"`, "m"))?.[1];

test("Shopify display names use Snapshot while installation, URLs, and extension handles stay stable", () => {
  const app = read("shopify.app.toml");
  assert.equal(tomlString(app, "name"), "Snapshot");
  assert.equal(
    tomlString(app, "client_id"),
    "be249e7dc1288f980804d0bf5e40cde0",
  );
  assert.equal(
    tomlString(app, "application_url"),
    "https://mousewhisperer.vercel.app",
  );
  assert.ok(
    app.includes(
      'redirect_urls = ["https://mousewhisperer.vercel.app/auth/callback"]',
    ),
  );
  assert.equal(
    tomlString(app, "url"),
    "https://mousewhisperer.vercel.app/api/track",
  );
  assert.equal(tomlString(app, "subpath"), "api");
  assert.equal(tomlString(app, "prefix"), "apps");

  for (const [directory, name, uid] of [
    [
      "tracking-embed",
      "Snapshot Tracker",
      "75aa2bb9-6264-a116-9f29-20e2f02eac340138f8fb",
    ],
    [
      "tracking-pixel",
      "Snapshot Conversions",
      "5d23d7eb-259c-2ecc-9355-3be596a7ce72d9323f16",
    ],
  ]) {
    const extension = read(`extensions/${directory}/shopify.extension.toml`);
    assert.equal(tomlString(extension, "name"), name);
    assert.equal(tomlString(extension, "uid"), uid);
    assert.equal(tomlString(extension, "handle"), directory);
  }
});

test("theme editor labels are renamed without changing the tracker bootstrap or compatibility detection", () => {
  const locale = JSON.parse(
    read("extensions/tracking-embed/locales/en.default.json"),
  );
  const liquid = read("extensions/tracking-embed/blocks/tracker.liquid");
  const schema = JSON.parse(
    liquid.match(/{% schema %}([\s\S]*?){% endschema %}/)[1],
  );
  assert.equal(locale.name, "Snapshot Tracker");
  assert.equal(schema.name, "Snapshot Tracker");
  assert.equal(schema.target, "body");
  assert.ok(liquid.includes('window.__TRACKING_API_ENDPOINT__ = "/apps/api"'));
  assert.ok(liquid.includes("'tracker.js' | asset_url"));
  const detection = read("app/utils/storefront-tracker-status.server.ts");
  assert.ok(detection.includes('html.includes("Snapshot Tracker")'));
  assert.ok(detection.includes('html.includes("Mouse Whisperer Tracker")'));
});

test("active UI, onboarding, analytics messages, and generated reports use the new app name", () => {
  const surfaces = [
    "app/root.tsx",
    "app/routes/_index/route.tsx",
    "app/routes/auth.login/route.tsx",
    "app/routes/app.tsx",
    "app/routes/app._index.tsx",
    "app/routes/app.channel-snapshots._index.tsx",
    "app/routes/app.channel-snapshots.$id.tsx",
    "app/routes/app.upgrade.tsx",
    "app/routes/app.ab-tests._index.tsx",
    "app/components/ConversionProgressCard.tsx",
    "app/utils/shopify-analytics.server.ts",
    "app/utils/export.server.ts",
    "app/utils/ab-tests.server.ts",
  ];
  for (const path of surfaces) {
    const content = read(path);
    assert.ok(
      content.includes("Snapshot"),
      `${path} must expose the current name`,
    );
    assert.doesNotMatch(
      content,
      /Mouse\s+Whisperer/,
      `${path} still contains previous display copy`,
    );
  }
  assert.match(read("app/root.tsx"), /title:\s*"Snapshot"/);
  assert.ok(
    read("app/routes/auth.login/route.tsx").includes("Log in to Snapshot"),
  );
  assert.doesNotMatch(
    read("app/routes/_index/route.tsx"),
    /\[your app\]|Product feature/,
  );
  assert.ok(
    read("app/utils/export.server.ts").includes("Report generated by Snapshot"),
  );
});

test("avatar display names change without replacing the legacy asset, template slot, or saved pixel data", () => {
  assert.match(
    read("app/components/PixelArtEditor.tsx"),
    /name:\s*"Snapshot",\s*data:\s*_cc\(\{\s*templateIdx:\s*6\s*\}\)/,
  );
  assert.match(
    read("app/components/AvatarParts.tsx"),
    /name:\s*"Snapshot",\s*pixels:\s*DS_MW_V1/,
  );
  const asset = readFileSync(
    new URL("../public/pixels/ds-mw-v1.pixil", import.meta.url),
  );
  assert.equal(
    createHash("sha256").update(asset).digest("hex"),
    "ccc415cce06c4e261a96e55ee5d4609556cb6acb77f19457a8403b4ceceba587",
  );
});

test("tracking cookies, attributes, source metadata, and generated-theme identifiers are not renamed", () => {
  const tracker = read("extensions/tracking-embed/assets/tracker.js");
  const pixel = read("extensions/tracking-pixel/src/index.js");
  for (const value of [
    "mw_sid",
    "mw_csid",
    "mw_rich_seen",
    "mw_acq",
    "mw_acquisition_v1",
    "_mw_sid",
    "_mw_csid",
  ]) {
    assert.ok(tracker.includes(value), `Tracker contract changed: ${value}`);
    assert.ok(pixel.includes(value), `Pixel contract changed: ${value}`);
  }
  for (const value of [
    "mw_session",
    "_mw_ab_test",
    "_mw_ab_variant",
    "data-mw-checkout-resumed",
    "mousewhisperer.vercel.app",
  ]) {
    assert.ok(tracker.includes(value), `Legacy contract changed: ${value}`);
  }
  const variants = read("app/utils/ab-tests.server.ts");
  assert.ok(
    variants.includes('class="mw-snapshot-variant" data-mw-source="snapshot"'),
  );
  assert.match(variants, /`mw-\$\{marker\}-\$\{readableSource\}-\$\{unique\}`/);
  assert.ok(variants.includes("MouseWhispererThemeFilesUpsert"));
  const preview = read("app/routes/api.template-preview.tsx");
  assert.ok(preview.includes("X-MW-Preview-Cache"));
  assert.ok(preview.includes("MouseWhispererPreview/1.0"));
});

